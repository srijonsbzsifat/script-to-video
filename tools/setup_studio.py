"""Install the cinema-2D studio (the aiTrends 2D Studio kit bundled in plugins/) into <repo>/studio.

  python -I tools/setup_studio.py            show what would be installed and exit (nothing is downloaded)
  python -I tools/setup_studio.py --go       install it
  options: --dir PATH (default <repo>/studio)   --skip-deps (copy files only, no npm/browser/pip downloads)

Downloads (about 1 GB, all kept inside the studio folder): npm packages (three.js, fonts, playwright), a headless
Chromium (~200 MB), and numpy + scipy for the sound synth. Needs Node >= 18, Python >= 3.9 and ffmpeg already on PATH.
Safe to re-run: existing files and projects are never overwritten.
"""
import argparse, pathlib, shutil, subprocess, sys

HERE = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE / "tools"))
import install_cinema_styles
from studio import studio_env

PLUGIN = HERE / "plugins" / "aitrends-2d-studio" / "skills" / "make-2d-video"
NOTES = """# Studio notes (generated by tools/setup_studio.py)

Cinema-2D engine. Pipeline docs: docs/make-2d-video/SKILL.md + references/. Hand-off from an episode:
`python -I <repo>/tools/to_studio.py <episode> --style <id>`. Run studio commands with `python -I <repo>/tools/studio.py run ...`
(it sets the browser and library paths).
- Nothing is installed or downloaded without asking. Timings come from script-to-video's local whisper.
- STYLE-AGNOSTIC RULE: every colour comes from mood()/S()/S().ui. No hard-coded white, black or neutral greys.
  Styles: dusk midnight golden neon storybook (dark kit) and daylight paper candy (light, ours).
- Before a full render: render a style grid (`--styles a,b --at t1,t2,t3 --scale 0.4`), look at it, run tools/lint_style_colors.py.
- Cost: about 7% of a Claude Pro 5-hour window per 30 s of finished video. Work in 60-90 s chapters.
"""


def need(cmd, hint):
    if not shutil.which(cmd):
        sys.exit(f"missing: {cmd}. {hint}")


def sh(cmd, cwd, env):
    print("  $", " ".join(map(str, cmd)))
    r = subprocess.run(cmd, cwd=cwd, env=env, shell=(sys.platform == "win32" and cmd[0] in ("npm", "npx")))
    if r.returncode:
        sys.exit(f"failed: {' '.join(map(str, cmd))}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=str(HERE / "studio"))
    ap.add_argument("--go", action="store_true")
    ap.add_argument("--skip-deps", action="store_true")
    a = ap.parse_args()
    d = pathlib.Path(a.dir).resolve()
    if not (PLUGIN / "kit" / "render.mjs").exists():
        sys.exit(f"plugin kit not found at {PLUGIN}")
    print(f"studio folder: {d}\nwill: copy the kit, copy its docs, install our light styles"
          + ("" if a.skip_deps else ", npm install, install headless Chromium, pip install numpy scipy (~1 GB download, inside the folder)"))
    if not a.go:
        print("\n(dry run) add --go to install.")
        return
    need("node", "install Node.js 18+ (https://nodejs.org)")
    need("ffmpeg", "install ffmpeg (winget install Gyan.FFmpeg / brew install ffmpeg)")
    if sys.version_info < (3, 9):
        sys.exit("Python 3.9+ needed")
    d.mkdir(parents=True, exist_ok=True)
    if not (d / "render.mjs").exists():
        shutil.copytree(PLUGIN / "kit", d, dirs_exist_ok=True)
    (d / "docs").mkdir(exist_ok=True)
    shutil.copytree(PLUGIN, d / "docs" / "make-2d-video", dirs_exist_ok=True, ignore=shutil.ignore_patterns("kit"))
    if not (d / "CLAUDE.md").exists():
        (d / "CLAUDE.md").write_text(NOTES, encoding="utf-8")
    sh([sys.executable, "tools/verify_kit.py"], d, studio_env(d))
    install_cinema_styles.main(str(d))
    if not a.skip_deps:
        env = studio_env(d)
        for p in (d / ".cache" / "npm", d / ".cache" / "pw", d / "pylibs"):
            p.mkdir(parents=True, exist_ok=True)
        sh(["npm", "install", "--no-audit", "--no-fund"], d, env)
        sh(["npx", "playwright", "install", "chromium"], d, env)
        sh([sys.executable, "-m", "pip", "install", "--quiet", "--target", str(d / "pylibs"), "numpy", "scipy"], d, env)
        sh(["node", "render.mjs", "--project", "examples/reaction-time", "--sheet", "--scale", "0.3"], d, env)
        shutil.rmtree(d / "examples" / "reaction-time" / "build", ignore_errors=True)
        print("self-test passed (14 stills rendered).")
    print(f"\nstudio ready: {d}\ncheck anytime: python -I tools/studio.py where")


if __name__ == "__main__":
    main()
